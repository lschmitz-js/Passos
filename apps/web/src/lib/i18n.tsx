export function useT() {
  const { locale } = useLocale();
  return (key: string, ...args: (string | number)[]) => {
    let s = DICT[locale][key] ?? DICT.pt[key] ?? key;
    args.forEach((arg, i) => {
      s = s.replace(`{${i}}`, String(arg));
    });
    return s;
  };
}

